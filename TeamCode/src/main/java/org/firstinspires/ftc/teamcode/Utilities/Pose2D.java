package org.firstinspires.ftc.teamcode.Utilities;

public class Pose2D {

    private double x;
    private double y;
    private double r;

    public Pose2D(double x, double y, double r) {
        this.x = x;
        this.y = y;
        this.r = r;
    }

    public double x(){
        return x;
    }

    public double y(){
        return y;
    }

    public double r(){
        return r;
    }

}
